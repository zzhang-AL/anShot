//
//  ScrollAxis.swift
//  AnShotCore
//
//  滚动截图的**增长轴**：长图沿哪一维变长。
//
//  ── 为什么单独成一个类型 ──────────────────────────────────
//
//  配准、世界坐标、拼接编排全部只认「行」——它们描述的是**竖直问题**。
//  横向长截图不重写这套逻辑，而是在入口把帧转置一次、出口再转置回来，
//  于是横向被映射成竖直（见 `ScrollshotImage.transposed()`）。
//
//  这意味着「轴」不属于内核，而属于**调用契约**：内核永远收到竖直帧，
//  轴只决定调用方转不转置。把它抽成一个明确的类型，是为了让「转置发生在
//  哪一层」这件事没有解释空间——散成 Bool 参数时，很容易出现
//  「入口转了、出口忘了转」这种半程错误，而它的症状（长图躺倒或被二次转置）
//  不会报错，只会让用户看到一张错图。
//

import Foundation

/// 滚动截图沿哪个方向增长。
public enum ScrollAxis: String, Sendable, CaseIterable, Codable {
    /// 竖向：内容向上滚，长图高度增长（最常见的网页/聊天记录场景）。
    case vertical
    /// 横向：内容向左滚，长图宽度增长（宽表格、时间轴、代码横向滚动）。
    case horizontal

    /// 长图在当前轴上的增长维度是否为「宽」。
    public var growsAlongWidth: Bool { self == .horizontal }
}

// ── 为什么不提供「按选区形状自动推断」 ──────────────────────
//
// 曾经有过 `ScrollAxis.infer(from:)`：宽 ≥ 高的 1.2 倍就当横向。
// 它是错的，而且是**静默错**——横向流程照样跑完，只给出一张内容被
// 横向拼接的错乱长图，用户看到的只是“怎么变横了”。
//
// 错在把两件无关的事当成一件：
// * 选区形状描述的是「看多大范围」；
// * 滚动方向描述的是「内容往哪边走」。
//
// 长对话、日志、聊天记录都是「宽而矮的选区 + 纵向滚动」，正是推断最容易
// 判反的场景。所以方向只能由调用方显式给出（当前实现：默认竖向，
// 按住 Option 点长截图 = 横向）。
